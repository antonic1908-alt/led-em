// config.h — піни та константи. ЄДИНЕ місце, де описано підключення.
// Аналогія з Unity: це як статичний клас з const-полями, який бачать усі скрипти.
// Якщо треба перенести датчик на інший пін — міняємо ТІЛЬКИ тут.

#pragma once          // «підключити цей файл лише один раз», навіть якщо його #include-ять з багатьох місць
                      // (у C# такої проблеми немає, бо там немає текстового #include)
#include <Arduino.h>  // базова бібліотека Arduino: типи uint8_t/uint32_t, pinMode, digitalRead, millis тощо

// ----------------------------------------------------------------------------
// Режим симуляції
// ----------------------------------------------------------------------------
// SIM_MODE=1 — збірка для Wokwi: замість VL53L0X використовується HC-SR04,
// а аналоговий датчик світла — фоторезисторний модуль Wokwi (LDR внизу дільника).
// Значення приходить з platformio.ini (env esp32c3_sim додає прапор -DSIM_MODE=1).
#ifndef SIM_MODE      // якщо компілятору НЕ передали SIM_MODE через прапор -D...
#define SIM_MODE 0    // ...вважаємо, що це звичайна збірка для реальної плати
#endif                // кінець умовного блоку препроцесора

// ----------------------------------------------------------------------------
// Піни
// ----------------------------------------------------------------------------
// #if ... #elif ... #else — це вибір на етапі КОМПІЛЯЦІЇ (як #if UNITY_ANDROID у Unity).
// У прошивку потрапить лише одна з гілок — та, для якої плати йде збірка.
#if defined(ARDUINO_ARCH_ESP32)   // PlatformIO сам визначає цей макрос при збірці для ESP32
// ESP32-C3 Super Mini. Логіка 3.3 В! Strapping-піни: 2, 8, 9.
// constexpr = константа, відома ще під час компіляції (як const у C#). Пам'яті RAM не займає.
constexpr int PIN_I2C_SDA    = 6;   // лінія даних шини I2C (BH1750, OLED, VL53L0X висять на ній разом)
constexpr int PIN_I2C_SCL    = 7;   // тактова лінія шини I2C
constexpr int PIN_LED_PWM    = 10;  // ШІМ на стрічку: -> 100 Ом -> затвор AO3400
constexpr int PIN_PIR        = 3;   // вихід датчика руху HC-SR501 OUT (видає 3.3 В — можна напряму)
constexpr int PIN_LIGHT_ADC  = 0;   // аналоговий вхід ADC1_CH0: дільник з фоторезистором або TEMT6000
constexpr int PIN_BTN_UP     = 4;   // кнопка «вгору» (другий контакт кнопки — на GND)
constexpr int PIN_BTN_DOWN   = 5;   // кнопка «вниз»
constexpr int PIN_BTN_OK     = 1;   // кнопка «OK / меню»
constexpr int PIN_BTN_MANUAL = 8;   // кнопка «ручний режим»; вбудований LED світиться при натисканні — це нормально
constexpr int PIN_US_TRIG    = 2;   // HC-SR04 TRIG — запуск ультразвукового імпульсу (опційно / у симуляції)
constexpr int PIN_US_ECHO    = 20;  // HC-SR04 ECHO — тривалість відлуння; у Wokwi цей пін називається "RX"

#elif defined(ARDUINO_ARCH_STM32) // а цей макрос визначається при збірці для STM32
// STM32F411CEU6 Black Pill. PA0 = кнопка KEY, PC13 = вбудований LED — їх не чіпаємо.
// На STM32 піни мають імена PB7, PA8... — це числа, які визначає ядро STM32duino, тому тип uint32_t.
constexpr uint32_t PIN_I2C_SDA    = PB7;   // I2C1 SDA
constexpr uint32_t PIN_I2C_SCL    = PB6;   // I2C1 SCL
constexpr uint32_t PIN_LED_PWM    = PA8;   // ШІМ стрічки: таймер TIM1, канал 1
constexpr uint32_t PIN_PIR        = PB0;   // вихід датчика руху
constexpr uint32_t PIN_LIGHT_ADC  = PA1;   // аналоговий вхід датчика світла
constexpr uint32_t PIN_BTN_UP     = PB12;  // кнопка UP
constexpr uint32_t PIN_BTN_DOWN   = PB13;  // кнопка DOWN
constexpr uint32_t PIN_BTN_OK     = PB14;  // кнопка OK
constexpr uint32_t PIN_BTN_MANUAL = PB15;  // кнопка MANUAL
constexpr uint32_t PIN_US_TRIG    = PB8;   // HC-SR04 TRIG
constexpr uint32_t PIN_US_ECHO    = PB9;   // HC-SR04 ECHO; цей пін толерантний до 5 В

#else                                       // будь-яка інша плата...
#error "Підтримуються лише ESP32 та STM32"  // ...зупиняємо компіляцію з цим повідомленням
#endif                                      // кінець вибору плати

// ----------------------------------------------------------------------------
// I2C-адреси
// ----------------------------------------------------------------------------
// На одній шині I2C кожен пристрій має свою «адресу» (як IP у мережі). 0x.. — шістнадцяткове число.
constexpr uint8_t I2C_ADDR_BH1750 = 0x23;  // датчик освітленості GY-302 (BH1750), пін ADDR на GND
constexpr uint8_t I2C_ADDR_OLED   = 0x3C;  // дисплей SSD1306 128x64
constexpr uint8_t I2C_ADDR_VL53   = 0x29;  // лазерний датчик дистанції VL53L0X

// ----------------------------------------------------------------------------
// ШІМ стрічки
// ----------------------------------------------------------------------------
constexpr uint32_t PWM_FREQ_HZ  = 20000;  // 20 кГц: вище за слух (нічого не пищить) і без мерехтіння на камері
constexpr uint8_t  PWM_BITS     = 10;     // роздільність 10 біт → значення від 0 до 1023 (2^10 - 1)
constexpr float    LED_GAMMA    = 2.2f;   // гамма-корекція: око сприймає яскравість нелінійно
                                          // (суфікс f = тип float, а не double — так швидше на МК)

// ----------------------------------------------------------------------------
// Аналоговий датчик світла
// ----------------------------------------------------------------------------
// Як саме підключений аналоговий датчик (від цього залежить формула перерахунку в lux):
// 0 = LDR між виходом і GND, 10k до 3V3 (так зроблено модуль у Wokwi)
// 1 = LDR між 3V3 і виходом, 10k до GND (РЕКОМЕНДОВАНО для ESP32-C3: у темряві напруга мала,
//     а АЦП ESP32-C3 точний лише до ~2.5 В)
// 2 = TEMT6000 (фототранзистор, 10k на модулі)
#ifndef ANALOG_LIGHT_KIND      // якщо не задано прапором -DANALOG_LIGHT_KIND=...
#if SIM_MODE                   // у симуляції...
#define ANALOG_LIGHT_KIND 0    // ...модуль Wokwi (LDR внизу)
#else                          // на реальній платі...
#define ANALOG_LIGHT_KIND 1    // ...рекомендована схема (LDR вгорі)
#endif                         // кінець #if SIM_MODE
#endif                         // кінець #ifndef ANALOG_LIGHT_KIND

constexpr float ADC_VREF_V      = 3.3f;      // напруга живлення дільника, В
constexpr float LDR_FIXED_OHM   = 10000.0f;  // постійний резистор дільника, Ом (10 кОм)
// Параметри фоторезистора: опір при 10 lux і «гамма» (нахил). Приблизні!
//   Wokwi:  RL10 = 50k, gamma = 0.7
//   GL5516: RL10 ≈ 5..10k, gamma ≈ 0.5
//   GM5528: RL10 ≈ 10..20k, gamma ≈ 0.6
#if SIM_MODE                                  // у симуляції беремо параметри фоторезистора Wokwi
constexpr float LDR_RL10_OHM = 50000.0f;      // опір при 10 lux, Ом
constexpr float LDR_GAMMA    = 0.7f;          // нахил характеристики
#else                                         // на реальній платі — GL5516
constexpr float LDR_RL10_OHM = 8000.0f;       // опір GL5516 при 10 lux, Ом
constexpr float LDR_GAMMA    = 0.5f;          // нахил характеристики GL5516
#endif                                        // кінець #if SIM_MODE

// ----------------------------------------------------------------------------
// Таймінги (мс)
// ----------------------------------------------------------------------------
// Як часто щось робимо в loop(). Ніяких delay(): порівнюємо millis() з часом останнього запуску.
constexpr uint32_t LIGHT_PERIOD_MS = 200;    // читати датчик світла 5 разів на секунду
constexpr uint32_t DIST_PERIOD_MS  = 120;    // читати дистанцію ~8 разів на секунду
constexpr uint32_t UI_PERIOD_MS    = 100;    // перемальовувати дисплей 10 разів на секунду
constexpr uint32_t LOG_PERIOD_MS   = 1000;   // друкувати рядок логу раз на секунду
constexpr uint32_t MENU_TIMEOUT_MS = 30000;  // через 30 с без натискань меню закривається само
